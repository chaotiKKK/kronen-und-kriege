def cache_path(cache: Path, relative: str) -> Path:
    cache = Path(cache).resolve()
    path = (cache / relative).resolve()
    if not path.is_relative_to(cache):
        raise ValueError('Armenian source cache path leaves its declared root')
    return path


def verify_file(path: Path, receipt: dict) -> None:
    raw = path.read_bytes()
    if len(raw)!=receipt['bytes'] or hashlib.sha256(raw).hexdigest()!=receipt['sha256']:
        raise ValueError('Changed Armenian original source byte count/hash: '+path.name)


def _clean(value):
    return re.sub(r'\s+',' ',html.unescape(re.sub('<[^>]+>',' ',value))).strip()


def _name(value):
    value=unicodedata.normalize('NFC',str(value)).removesuffix(' համայնք').strip()
    return NAME_ALIASES.get(value,value)


def parse_official_communities(document: str) -> list[dict]:
    """Appendix2 first-column identities, not settlements or obsolete appendices."""
    result=[]
    for index,table in enumerate(re.findall(r'<table\b[^>]*>.*?</table>',document,re.I|re.S)):
        rows=re.findall(r'<tr\b[^>]*>.*?</tr>',table,re.I|re.S)
        if not rows or not all(term in _clean(rows[0]) for term in ['Համայնքի անվանումը','Բնակավայր']):
            continue
        for row in rows[1:]:
            cells=[_clean(x) for x in re.findall(r'<td\b[^>]*>(.*?)</td>',row,re.I|re.S)]
            if len(cells)>=2 and re.match(r'^\d+\.',cells[0]):
                result.append({'name':re.sub(r'^\d+\.\s*','',cells[0]),'legal_row':cells[0],
                    'first_settlement':cells[1],'table_index':index,'source':LAW})
    result.append({'name':'Երևան','article':'6.1','source':LAW})
    return result


def qualify_record(properties: dict, relation: dict, legal_names: set, district_names: set) -> tuple[str,str]:
    """Positive native identity proof; the provider ADM number is insufficient."""
    identifier=int(properties['osm_id']);tags=relation.get('tags',{})
    level=properties.get('code',0)-1200
    if (relation.get('id')!=identifier or not isinstance(relation.get('version'),int)
            or relation['version']<1 or not relation.get('timestamp') or relation['timestamp']>SNAPSHOT
            or tags.get('boundary')!='administrative' or tags.get('name')!=properties.get('name')
            or tags.get('admin_level')!=str(level) or properties.get('fclass')!='admin_level'+str(level)
            or tags.get('is_in:country_code','AM').upper()!='AM' or tags.get('addr:country','AM').upper()!='AM'):
        raise ValueError('Armenian source identity/country/admin-level/snapshot contradiction')
    name=_name(tags['name'])
    if identifier in DISTRICT_IDS:
        english=DISTRICT_ALIASES.get(tags.get('name:en'),tags.get('name:en'))
        if level!=5 or english not in district_names:
            raise ValueError('Unproved Yerevan administrative district identity')
        return 'local_admin',tags['name']
    if identifier==364087 and level==4 and name=='Երևան' and name in legal_names:
        return 'region',name
    if level==5 and (name in legal_names or FORMER_NAMES.get(identifier)==name):
        return 'municipality',name
    raise ValueError('Source object is not a positively identified current Armenian community')


def merge_current_geometries(rows: list[dict]) -> list[dict]:
    """Dissolve only the two enacted September2026 pairs, keeping source IDs."""
    by_id={int(r['osm_relation_id']):r for r in rows}
    if len(by_id)!=len(rows):
        raise ValueError('Duplicate Armenian source relation identifier')
    removed=set();replacements={}
    for primary,parts in MERGERS.items():
        if not any(p in by_id for p in parts):
            continue
        if not all(p in by_id for p in parts):
            raise ValueError('Missing original component of enacted Armenian merger')
        merged=dict(by_id[primary]);merged['geometry']=unary_union([by_id[p]['geometry'] for p in parts])
        merged.update(source_part_ids=['r'+str(p) for p in parts],
            source_part_versions=[{'id':p,'version':by_id[p]['osm_relation_version'],
                'timestamp':by_id[p]['source_timestamp']} for p in parts],
            legal_geometry_dissolve=True,geometry_modified_by_importer=True,
            geometry_modification='Union of the two original polygon components under enacted HO454-N; no gap allocation',
            merger_law=MERGER_LAW,merger_effective_date='2026-09-19')
        if not merged['geometry'].is_valid or merged['geometry'].is_empty:
            raise ValueError('Enacted Armenian merger has invalid source-union geometry')
        replacements[primary]=merged;removed.update(parts[1:])
    return [replacements.get(int(r['osm_relation_id']),r) for r in rows if int(r['osm_relation_id']) not in removed]


def api_polygon(payload: dict):
    """Build Chambarak from actual, snapshot-checked way and node members."""
    relations=full_geometry_relations(payload,SNAPSHOT)
    r=relations.get(10853047,{})
    if (r.get('tags',{}).get('boundary')!='administrative' or r['tags'].get('admin_level')!='5'
            or _name(r['tags'].get('name'))!='Ճամբարակ'):
        raise ValueError('Unproved Chambarak boundary relation')
    outer,inner=_member_lines(r,relations)
    shells=_closed_polygons(outer,10853047,'outer')
    holes=_closed_polygons(inner,10853047,'inner') if inner else []
    exterior=unary_union(shells)
    if holes and unary_union(holes).difference(exterior).area>1e-12:
        raise ValueError('Chambarak inner ring outside its actual exterior')
    geometry=unary_union([s.difference(unary_union([h for h in holes if s.covers(h)])) for s in shells])
    if geometry.is_empty or not geometry.is_valid or geometry.geom_type not in ('Polygon','MultiPolygon'):
        raise ValueError('Chambarak members do not form valid original area geometry')
    return geometry,r


def _district_names(document):
    names=set()
    for attributes,text in re.findall(r'<a\b([^>]*?)>(.*?)</a>',document,re.I|re.S):
        if re.search(r'href=[\"\']/en/districts/',attributes):
            names.add(_clean(text))
    if len(names)!=12:
        raise ValueError('The official Yerevan district directory changed')
    return names


