def prepare_sources(cache: Path=DEFAULT_CACHE) -> list[dict]:
    cache=Path(cache);_download_inputs(cache)
    rows,identities=_read_rows(cache)
    sources=_source_records(rows)
    manifest={'schema':1,'sources':sources,'official_role_identities':identities,
        'note':'Current legal identity set, partial geometric land coverage; original law text stays outside runtime manifests.'}
    (ROOT/'data/atlas_armenia_sources.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    return sources


def iter_boundaries(cache: Path, sources: list[dict]):
    """Verify every original input offline and return independent Shapely rows."""
    selected={s.get('id') for s in sources}
    if not selected or not selected.issubset({SOURCE_ID,SUPPLEMENT_ID}) or len(selected)!=len(sources):
        raise ValueError('Unknown or duplicate Armenian provider source')
    rows,_=_read_rows(Path(cache))
    expected={s['id']:s for s in _source_records(rows)}
    for source in sources:
        if source!=expected[source['id']]:
            raise ValueError('Changed Armenian source identity/provenance/roles')
    yield from (row for row in rows if row['source'] in selected)


