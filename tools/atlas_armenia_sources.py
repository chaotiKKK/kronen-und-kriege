def _download_inputs(cache: Path):
    archive_files=[r for r in PINNED_INPUTS if r.get('archive_member')]
    missing=[]
    for receipt in archive_files:
        target=cache_path(cache,receipt['cache_file'])
        if not target.exists():
            staged=cache/'geofabrik-am-stage/armenia/members'/receipt['archive_member']
            if staged.exists():
                verify_file(staged,receipt);target.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(staged,target)
            else:missing.append(receipt)
    if missing:
        remote=RangeSource(_input(cache,'remote-zip'),ARCHIVE)
        with zipfile.ZipFile(RemoteZip(remote.snapshot['bytes'],remote.fetch)) as archive:
            for receipt in missing:
                payload=archive.read(receipt['archive_member']) # Original ZIP CRC checked by ZipFile.
                if len(payload)!=receipt['bytes'] or hashlib.sha256(payload).hexdigest()!=receipt['sha256']:
                    raise ValueError('Changed original Geofabrik Armenian ZIP member')
                target=cache_path(cache,receipt['cache_file']);target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(payload)
    for receipt in PINNED_INPUTS:
        target=cache_path(cache,receipt['cache_file'])
        if not target.exists():
            target.parent.mkdir(parents=True,exist_ok=True)
            result=subprocess.run(['curl.exe','--fail','--location','--silent','--show-error','--connect-timeout','15',
                '--max-time','45','--max-filesize',str(receipt['bytes']+1),'--output',str(target),receipt['url']],
                capture_output=True,text=True)
            if result.returncode:
                raise RuntimeError('Armenian pinned source download failed: '+result.stderr)
        verify_file(target,receipt)


